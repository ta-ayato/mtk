.global outbyte

.text
.even

***************************************************************
** outbyte : 1文字出力関数 (C側 write() から呼び出し)
**   【引数】  4(%sp).L : 出力文字 (char型を32bitに拡張してpush, 下位1バイトが対象)
**   【戻り値】なし
**   【使用 syscall】PUTSTRING (= 2)
**     入力: %D1.L = ch (0: UART1), %D2.L = buf先頭アドレス, %D3.L = 出力文字数
**     出力: %D0.L = 実際に送信した文字数 (1文字出力できるまでリトライ)
***************************************************************
outbyte:
	* 破壊するレジスタ (%d0-%d3) をサブルーチン開始直後に退避 (4本 × 4バイト = 16バイト)
	* 退避前の引数位置は 4(%sp) だったが、16バイト下がったため引数は 20(%sp) にずれる
	* ビッグエンディアン(32bit拡張)の下位1バイトは 20 + 3 = 23(%sp) に格納されている
    * (32bitを4バイトに分けた時、最上位のbaseから4バイト目)
	movem.l	%d0-%d3, -(%sp)

	* 出力対象の1バイトを指すアドレスを %d2 にセット
	lea	23(%sp), %d2 * レジスタ退避(4 * 4) + 引数位置4 + baseからのバイト3 = 23

outbyte_retry:
	move.l	#2, %d0                 | システムコール番号 2 = PUTSTRING
	move.l	#0, %d1                 | ch = 0 (UART1)
	move.l	#1, %d3                 | 出力文字数 = 1
	trap	#0                      | PUTSTRING システムコール呼び出し

	* 1文字送信できたか確認 (戻り値 %d0.L == 1 で完了、それ以外はリトライ)
	cmpi.l	#1, %d0
	bne	outbyte_retry

	* 退避したレジスタ (%d0-%d3) を復元して呼び出し元へ戻る
	movem.l	(%sp)+, %d0-%d3
	rts