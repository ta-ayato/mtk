.global inbyte
.global inkey

.text
.even

***************************************************************
** inbyte : 1文字入力関数 (C側 read() から呼び出し)
**   【引数】  なし
**   【戻り値】%D0.B (または %D0.L) : 受信した1文字 (8bit ASCII)
**   【使用 syscall】SYSCALL_NUM_GETSTRING (= 1)
**     入力: %D1.L = ch (0: UART1), %D2.L = buf先頭アドレス, %D3.L = 最大取得数
**     出力: %D0.L = 実際に取得した文字数 (0 なら受信キューが空)
***************************************************************
inbyte:
	* GETSTRING で使うレジスタ (%D1-%D3) と、inbyte専用の作業領域を退避
	* (%D0 は戻り値を返すため退避しない)
	movem.l	%d1-%d3, -(%sp)
	subq.l	#4, %sp                 
	* スタック上に 1文字分のバッファ領域 (4バイト確保, 先頭 %sp) を作成

inbyte_retry:
    *trap #0のための準備とtrap #0
	move.l	#1, %d0                 | システムコール番号 1 =GETSTRING
	move.l	#0, %d1                 | ch = 0 (UART1)
	move.l	%sp, %d2                | 書き込み先バッファアドレス = スタック上の領域
	move.l	#1, %d3                 | 最大 1 文字取得
	trap	#0                      | getstringシステムコール呼び出し (戻り値: %D0.L = 取得文字数)

	* 受信キューが空 (取得文字数 == 0) の場合は、1文字入るまでd0.lに何か入るまで再試行
	* (GETSTRING は入力待ちをせず 0 を返す仕様のため)
	cmpi.l	#1, %d0
	bne	inbyte_retry

	* バッファに格納された受信1文字 (1バイト) を %D0 の下位バイトへ読み出し
	* 上位ビットにゴミが残らないようゼロ拡張しておく
	moveq.l	#0, %d0 * 一旦クリア
	move.b	(%sp), %d0

	* スタック領域の解放と、退避したレジスタ (%D1-%D3) の復元
	* さっきの4バイト解法
	addq.l	#4, %sp
	movem.l	(%sp)+, %d1-%d3
	rts

***************************************************************
** inkey(ch) : 非待機1文字入力関数 (Option)
**   【引数】  4(%sp).L : シリアルポート番号 ch
**   【戻り値】%D0.L      : 入力あり -> 0x00000000〜0x000000ff (符号なし文字)
**                        入力なし -> -1 (0xffffffff)
***************************************************************
inkey:
	** 呼び出し直後の 4(%sp) から引数 ch を %d1 に取得する
	move.l	4(%sp), %d1

	** GETSTRING で使う %d2-%d3 と、1文字受信バッファ用のスタック領域を退避・確保
	** (%d0 は戻り値を返すため退避しない)
	movem.l	%d2-%d3, -(%sp)
	subq.l	#4, %sp                 
	** スタック上に 1文字分のバッファ領域 (先頭 %sp) を確保

	** GETSTRING (syscall #1) を発行 (%d1 にはすでに ch が入っている)
	move.l	#1, %d0                 | システムコール番号 1 (GETSTRING)
	move.l	%sp, %d2                | 受信データの書き込み先アドレス = スタックバッファ先頭
	move.l	#1, %d3                 | 最大 1 文字取得
	trap	#0                      | 戻り値 %d0.L = 取得した文字数 (0 または 1

	** 取得文字数が 0 なら入力なしとして -1 (0xffffffff) を返す
	tst.l	%d0
	beq	inkey_no_input

	** 1文字取得できた場合は、符号なし 32bit 値 (0x00000000〜0x000000ff) として %d0 に格納
	moveq.l	#0, %d0
	move.b	(%sp), %d0
	bra	inkey_exit

inkey_no_input:
	** 入力がない場合は -1 を設定
	moveq.l	#-1, %d0

inkey_exit:
	** 確保したスタック領域を解放し、退避したレジスタ (%d2-%d3) を復元
	addq.l	#4, %sp
	movem.l	(%sp)+, %d2-%d3
	rts
